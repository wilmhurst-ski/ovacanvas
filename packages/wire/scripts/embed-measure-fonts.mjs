/**
 * The engine's text font as TTF, for measuring text in Node.
 *
 * Usage: node scripts/embed-measure-fonts.mjs
 *
 * The engine draws text in the variable Roboto embedded in
 * `@ovacanvas/2d` (`src/lib/theme/fonts/roboto.ts`, WOFF2). fontkit cannot
 * apply a weight to a WOFF2 variable font, so this decompresses those same
 * faces to TTF - one source, two encodings - and writes them as base64 to
 * `src/measure/roboto-ttf.ts`. Run it after `embed-fonts.mjs` in 2d.
 */
import fs from 'fs';
import path from 'path';
import {fileURLToPath, pathToFileURL} from 'url';
import wawoff2 from 'wawoff2';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SOURCE = path.resolve(HERE, '../../2d/lib/theme/fonts/roboto.js');
const OUT = path.resolve(HERE, '../src/measure/roboto-ttf.ts');

const {ROBOTO_FACES} = await import(pathToFileURL(SOURCE).href);
const faces = [];
for (const face of ROBOTO_FACES) {
  const ttf = await wawoff2.decompress(Buffer.from(face.woff2, 'base64'));
  faces.push({...face, ttf: Buffer.from(ttf).toString('base64')});
}
fs.writeFileSync(
  OUT,
  `/* eslint-disable */
// Generated by scripts/embed-measure-fonts.mjs from the engine's embedded
// Roboto (SIL Open Font License 1.1, packages/2d/src/lib/theme/fonts).
// Do not edit.

export const ROBOTO_TTF: readonly {
  readonly subset: string;
  readonly unicodeRange: string;
  /** The TTF file, base64. */
  readonly ttf: string;
}[] = [
${faces
  .map(
    f =>
      `  {\n    subset: '${f.subset}',\n    unicodeRange: '${f.unicodeRange}',\n    ttf: '${f.ttf}',\n  },`,
  )
  .join('\n')}
];
`,
);
console.log(`wrote ${faces.length} TTF faces`);
