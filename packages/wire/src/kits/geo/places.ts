/**
 * A continent or region: the countries in it and, for continents, the
 * lon/lat window a map of it should show (members with far-flung
 * territories - France, the USA, Russia - would otherwise stretch the view).
 */
export interface PlaceGroup {
  readonly members: readonly string[];
  /** [west, south, east, north] in degrees. */
  readonly view?: readonly [number, number, number, number];
}

